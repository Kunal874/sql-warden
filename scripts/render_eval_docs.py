"""Render README results, docs/EVAL.md and docs/RESUME.md from the tracked summary only."""

from __future__ import annotations

import re
from typing import Any

LABEL = {
    "full_n1": "Full schema, 1 candidate",
    "ret_n1_k0": "Retrieval (24 columns), 1 candidate",
    "ret_n1_k1": "Retrieval + 1 repair",
    "ret_n3_k0": "Retrieval, 3-candidate vote",
    "ret_n3_k1": "Retrieval + repair + 3-candidate vote (full loop)",
    "messy_n1": "Messy column/table names, 1 candidate",
    "orig_n1_k0": "Original BIRD wording, 1 candidate",
    "orig_n3_k1": "Original BIRD wording, full loop",
}
CLAIM = (
    "Local PostgreSQL-adapted BIRD Mini-Dev subset with corrected labels and a 4-bit 7B "
    "model; not an official BIRD score."
)


def pct(value: float | None) -> str:
    return "—" if value is None else f"{value * 100:.1f}%"


def interval(value: dict | None) -> str:
    if not value or value.get("low") is None:
        return "—"
    return f"{pct(value['low'])}–{pct(value['high'])}"


def signed(value: float | None) -> str:
    return "—" if value is None else f"{'+' if value >= 0 else ''}{value * 100:.1f} pp"


def condition_table(split: dict[str, Any]) -> list[str]:
    lines = [
        "| Setting | Correct | EX | 95% CI (exact) | Answered | EX when answered |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for key, label in LABEL.items():
        c = split["conditions"].get(key)
        if not c:
            continue
        pending = f" ({c['pending']} pending)" if c.get("pending") else ""
        lines.append(
            f"| {label} | {c['ex']['count']}/{c['n']}{pending} | {pct(c['ex']['rate'])} | "
            f"{interval(c['ex'].get('exact'))} | {pct(c['answered']['rate'])} | "
            f"{pct(c['answered_only_ex']['rate'])} |"
        )
    return lines


def comparison_table(split: dict[str, Any]) -> list[str]:
    lines = [
        "| Comparison (same questions) | Difference | 95% bootstrap CI | Only left | Only right |",
        "| --- | --- | --- | --- | --- |",
    ]
    for c in split.get("comparisons", {}).values():
        lines.append(
            f"| {LABEL.get(c['left'], c['left'])} vs {LABEL.get(c['right'], c['right'])} | "
            f"{signed(c['difference'])} | {interval(c['ci'])} | {c['left_only']} | "
            f"{c['right_only']} |"
        )
    return lines


def threshold_line(split: dict[str, Any]) -> str | None:
    coverage = split.get("accuracy_coverage")
    if not coverage or not coverage.get("frozen_threshold"):
        return None
    point = next(
        (p for p in coverage["curve"] if p["threshold"] == coverage["frozen_threshold"]), None
    )
    if not point:
        return None
    return (
        f"With the development-chosen agreement threshold {coverage['frozen_threshold']}, the "
        f"loop answers {pct(point['coverage'])} of these questions and is correct on "
        f"{pct(point['selective_ex'])} of the ones it answers (end-to-end "
        f"{pct(point['end_to_end_ex'])})."
    )


def readme_block(summary: dict[str, Any]) -> str:
    lines = [CLAIM, ""]
    for name, title in (("held_out", "Held-out"), ("dev", "Development")):
        split = summary["splits"].get(name)
        if not split:
            continue
        primary = ", primary" if name == "held_out" else ", used for calibration"
        lines += [f"**{title} ({split['ids']} questions{primary})**", ""]
        lines += condition_table(split) + [""]
        if name == "held_out":
            for c in split.get("comparisons", {}).values():
                lines.append(
                    f"- {LABEL.get(c['left'], c['left'])} vs {LABEL.get(c['right'], c['right'])}: "
                    f"{signed(c['difference'])} (95% CI {interval(c['ci'])}, n={c['n']})."
                )
            line = threshold_line(split)
            if line:
                lines.append(f"- {line}")
            latency = split.get("latency", {}).get("ret_n3_k1", {})
            if latency.get("median_item_seconds"):
                lines.append(
                    f"- Full loop median {latency['median_item_seconds']} s per question on an "
                    f"RTX 4060 laptop GPU; peak VRAM {gb(latency.get('peak_vram_bytes'))}."
                )
            lines.append("")
    return "\n".join(lines).rstrip()


def replace_block(text: str, block: str) -> str:
    pattern = re.compile(r"(<!-- results:start -->\n).*?(\n<!-- results:end -->)", re.S)
    return pattern.sub(lambda m: m.group(1) + block + m.group(2), text, count=1)


def gb(value: int | None) -> str:
    return "—" if not value else f"{value / 1e9:.1f} GB"


def render_eval(summary: dict[str, Any], *, e0: dict[str, Any]) -> str:
    out = [
        "# Evaluation evidence",
        "",
        f"{CLAIM} Generated by `scripts/build_matrix_report.py` from tracked summaries;",
        "raw runs, generated SQL and caches stay local and ignored.",
        "",
        "## Protocol",
        "",
        "- Pool: 424 verified corrected BIRD Mini-Dev questions over 11 databases (C1, D-053).",
        "- Split: frozen development slice of 100 and held-out set of 324 (D-054). Settings",
        "  and the agreement threshold were chosen on development only; held-out is primary.",
        "- Contract v2 (D-075): corrected evidence + question, paper-structure prompts,",
        "  quoted identifiers, reasoning before the final SQL block, guard allowlist D-076.",
        "- Model: Arctic-Text2SQL-R1-7B Q4_K_M via local Ollama; candidate 0 greedy,",
        "  candidates 1-2 sampled at temperature 0.7 with distinct seeds; one repair.",
        "- Scoring: the pinned official BIRD EX rule on complete results. Abstentions,",
        "  blocks and failures count as wrong; missing records are reported as pending.",
        "- Intervals: exact Clopper-Pearson for rates; paired bootstrap (10,000 resamples,",
        "  seed 20261008) for differences on the same questions. Multiple ablation",
        "  comparisons are exploratory; no multiplicity correction was predefined.",
        "",
        "## E0 — historical smoke (contract v1)",
        "",
        "Question only, JSON-only output, full schema, 100 development questions:",
        f"Arctic {pct(e0.get('arctic', {}).get('ex'))}, Qwen {pct(e0.get('qwen', {}).get('ex'))}.",
        "Superseded by contract v2 for every experiment below.",
    ]
    for name, title in (("held_out", "Held-out"), ("dev", "Development")):
        split = summary["splits"].get(name)
        if not split:
            continue
        out += ["", f"## E2 — loop ablation, {title.lower()} ({split['ids']} questions)", ""]
        out += condition_table(split) + [""] + comparison_table(split)
        out += phase_section(split)
        repairs = split.get("repair_outcomes")
        if repairs and repairs["repaired_candidates"]:
            out += [
                "",
                f"Repair outcomes ({repairs['repaired_candidates']} repaired candidates; "
                "the repair prompt receives only the sanitized failure category): "
                + fmt_counts(repairs["outcomes"])
                + ".",
            ]
        if split.get("label_rescoring"):
            out += ["", f"## E1/E3 — original versus corrected labels, {title.lower()}", ""]
            out += [
                "Same predictions scored against both label sets where the original",
                "PostgreSQL gold was verified against SQLite; excluded items are listed.",
                "",
                "| Run | Scored | Correct (corrected) | Correct (original) | Only corrected | "
                "Only original | Excluded |",
                "| --- | --- | --- | --- | --- | --- | --- |",
            ]
            for run, r in split["label_rescoring"].items():
                out.append(
                    f"| {LABEL.get(run, run)} | {r['scored_both']} | "
                    f"{r['correct_under_corrected']} | {r['correct_under_original']} | "
                    f"{r['correct_only_under_corrected']} | {r['correct_only_under_original']} | "
                    f"{fmt_counts(r['excluded_original_label'])} |"
                )
        if split.get("input_change"):
            change = split["input_change"]
            out += [
                "",
                "Separate run with the original BIRD wording on the "
                f"{change['changed_items']} questions whose wording or evidence changed:",
                f"single candidate {signed(change['single_candidate']['difference'])} "
                f"(CI {interval(change['single_candidate']['ci'])}), full loop "
                f"{signed(change['full_loop']['difference'])} "
                f"(CI {interval(change['full_loop']['ci'])}), original minus corrected.",
                "This is an input change, so the gain is not attributed to labels alone.",
            ]
        if split.get("messy_schema"):
            messy = split["messy_schema"]
            out += [
                "",
                f"## E4 — messy schema names, {title.lower()}",
                "",
                "Seeded cryptic table/column names; the model sees only those and its SQL is",
                "translated back before the guard. All 424 gold queries return identical rows",
                "after the round trip (`results/G3_matrix/messy-gold-check.json`); "
                f"{messy['leaked_names']} distinctive original names leaked into prompts; "
                f"{messy['translated']} outputs translated, {messy['untranslated']} not.",
            ]
        if split.get("clarification"):
            c = split["clarification"]
            out += [
                "",
                f"## E7 — clarification, {title.lower()} (oracle-assisted)",
                "",
                f"{c['label']}. Asked on {c['asked']} of {c['items']} questions after the",
                "original wording abstained. Ask rate on annotated ambiguity candidates "
                f"{pct(c['ask_rate_on_ambiguity_candidates'])}, on clear negatives "
                f"{pct(c['ask_rate_on_clear_negatives'])} (false asks). Helper options valid "
                f"{pct(c['helper_valid_options'])}; helper median {c['helper_median_seconds']} s "
                f"with median swap {c['helper_median_swap_seconds']} s. After the oracle reply: "
                f"{c['answered_after_oracle']} answered, {c['correct_after_oracle']} correct of "
                f"{c['oracle_replies']}.",
                "",
                "Ask rate by audited reason (`docs/ambiguity-audit.json`):",
                "",
                "| Audited class | Questions | Asked | Ask rate |",
                "| --- | --- | --- | --- |",
                *[
                    f"| {name.replace('_', ' ')} | {v['n']} | {v['asked']} | {pct(v['ask_rate'])} |"
                    for name, v in c.get("ask_rate_by_audited_class", {}).items()
                ],
            ]
        cases = split.get("case_studies") or {}
        if cases.get("label_change") or cases.get("input_change"):
            out += [
                "",
                f"## E3 — case studies, {title.lower()}",
                "",
                "Label change: the same full-loop answer is scored against both label sets.",
                "Input change: the single-candidate answer for original versus corrected",
                "wording. Reasons come from the audit; question text is not reproduced.",
                "",
                "| Question ID | Kind | Correct under / with | Audited reason |",
                "| --- | --- | --- | --- |",
                *[
                    f"| {c['question_id']} | label change | {c['correct_under']} labels | "
                    f"{c['change_reason'].replace('_', ' ')} |"
                    for c in cases.get("label_change", [])
                ],
                *[
                    f"| {c['question_id']} | input change | {c['correct_with']} | "
                    f"{(c['change_reason'] or '').replace('_', ' ')} |"
                    for c in cases.get("input_change", [])
                ],
            ]
        if split.get("accuracy_coverage"):
            coverage = split["accuracy_coverage"]
            out += [
                "",
                f"## E8 — agreement threshold, {title.lower()}",
                "",
                "| Agreement at least | Coverage | EX when answered | End-to-end EX |",
                "| --- | --- | --- | --- |",
            ]
            out += [
                f"| {p['threshold']} | {pct(p['coverage'])} | {pct(p['selective_ex'])} | "
                f"{pct(p['end_to_end_ex'])} |"
                for p in coverage["curve"]
            ]
            out.append(
                "Frozen development threshold (D-078, `docs/e8-threshold.json`): "
                f"{coverage.get('frozen_threshold') or 'not frozen'}."
            )
        out += latency_section(split, title)
        out += [
            "",
            f"Failure categories for the full loop ({title.lower()}): "
            + fmt_counts(split.get("failure_taxonomy", {}))
            + ". Labels: `results/G3_matrix/failure-labels.json`.",
        ]
    out += self_authored_section(summary.get("e7_self_authored"))
    security = summary.get("security") or {}
    out += [
        "",
        "## E5 — attacks",
        "",
        "All-layers-on evidence: [SECURITY](../SECURITY.md) and `docs/attack-suite-manifest.json`.",
    ]
    if security:
        bound = security["success_rate_exact_95"]
        out.append(
            f"{security['succeeded']} of {security['attacks']} recorded attacks succeeded "
            f"(exact 95% interval {pct(bound['low'])}–{pct(bound['high'])}); this bounds the "
            "recorded suite only, not future attacks."
        )
    out += layer_off_section(summary.get("layer_off"))
    out += ["", "## E9 — fine-tuning", "", "Optional (G6) and not run.", ""]
    return "\n".join(out)


def self_authored_section(e7: dict[str, Any] | None) -> list[str]:
    if not e7:
        return []
    lines = [
        "",
        "## E7 — self-authored ambiguity set (simulated user, not oracle)",
        "",
        "Frozen before evaluation (`docs/e7-self-authored.json`, check file records its",
        "SHA-256). The simulated reply is the frozen intended meaning; it never sees",
        "candidate SQL or results. Evaluation partition is primary; tuning is shown too.",
        "",
        "| Partition / kind | n | Asked | Correct without asking | Correct final | "
        "Asked then correct | Asked then wrong |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for name, v in e7.items():
        lines.append(
            f"| {name.replace('_', ' ')} | {v['n']} | {v['asked']} | "
            f"{v['correct_without_asking']} | {v['correct_final']} | "
            f"{v['asked_then_correct']} | {v['asked_then_wrong']} |"
        )
    readings = [
        f"{name.replace('_', ' ')}: first answer matched {fmt_counts(v['first_reading'])}"
        for name, v in e7.items()
        if "first_reading" in v
    ]
    if readings:
        lines += ["", "Reading chosen before any clarification (A/B/neither/None=no answer): "]
        lines += [f"- {line}" for line in readings]
    return lines


def layer_off_section(layer_off: dict[str, Any] | None) -> list[str]:
    if not layer_off:
        return ["Layer-off variants: not run."]
    lines = [
        "",
        "Layer-off variants in the disposable environment "
        f"(`{layer_off['project']}`, synthetic canaries, no real credentials):",
        "",
        "| Configuration | Attacks | Prevented | Canary exposed or changed | Stopped by |",
        "| --- | --- | --- | --- | --- |",
    ]
    for name, v in layer_off["configurations"].items():
        lines.append(
            f"| {name.replace('_', ' ')} | {v['attacks']} | {v['prevented']} | "
            f"{v['succeeded']} | {fmt_counts(v['stopped_by'])} |"
        )
    through = layer_off["succeeded_with_one_layer_off"]
    prevented = layer_off["prevented_with_any_one_layer_off"]
    gaps = ", ".join(f"{attack} ({', '.join(configs)})" for attack, configs in through.items())
    return lines + [
        "",
        f"{len(prevented)} of {len(prevented) + len(through)} attacks stayed prevented with "
        f"any single layer off. Let through by one layer off: {gaps or 'none'}.",
    ]


def phase_section(split: dict[str, Any]) -> list[str]:
    rates = split.get("phase_rates", {})
    if not rates:
        return []
    lines = [
        "",
        "First-attempt phase rates per candidate:",
        "",
        "| Run | Candidates | SQL extracted | Guard accepted | Executed | Top failure reasons |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for run, r in rates.items():
        top = dict(
            sorted(
                r["first_attempt_failure_reasons"].items(), key=lambda item: (-item[1], item[0])
            )[:4]
        )
        lines.append(
            f"| {run} | {r['candidates']} | {pct(r['sql_extracted'])} | "
            f"{pct(r['guard_accepted'])} | {pct(r['executed'])} | {fmt_counts(top)} |"
        )
    return lines


def latency_section(split: dict[str, Any], title: str) -> list[str]:
    rows = []
    for run, value in split.get("latency", {}).items():
        generate = (value.get("per_role") or {}).get("generate", {})
        if not value.get("items") or "median_item_seconds" not in value:
            continue
        rows.append(
            f"| {run} | {value['items']} | {value.get('calls_per_question', '—')} | "
            f"{value.get('completion_tokens_total', '—')} | "
            f"{value.get('median_item_seconds')} s | "
            f"{value.get('p95_item_seconds')} s | {generate.get('median_seconds', '—')} s | "
            f"{generate.get('median_completion_tokens', '—')} | {value.get('cache_hits')} | "
            f"{gb(value.get('peak_vram_bytes'))} |"
        )
    if not rows:
        return []
    return [
        "",
        f"## E6 — latency and cost (E2 inference cost), {title.lower()}",
        "",
        "Fresh local calls only; cache hits are exact replays and are not live latency.",
        "Measured on a shared laptop while other local work ran, so treat as indicative.",
        "",
        "| Run | Questions | Model calls per question | Output tokens total | Median per question "
        "| p95 | Median per call | Output tokens per call | Cache hits | Peak VRAM |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
        *rows,
    ]


def render_resume(summary: dict[str, Any]) -> str:
    split = summary["splits"].get("held_out") or summary["splits"].get("dev") or {}
    name = "held-out" if "held_out" in summary["splits"] else "development"
    loop = split.get("conditions", {}).get("ret_n3_k1")
    full = split.get("conditions", {}).get("full_n1")
    lines = [
        "# Resume evidence",
        "",
        f"Generated from `results/G3_matrix/summary.json`. {CLAIM}",
        "",
        "- Built SQLWarden, a local read-only text-to-SQL agent (FastAPI, PostgreSQL 16,",
        "  sqlglot, React) with a SQL guard, per-dataset read-only logins, bounded execution,",
        "  repair, result voting, clarification and abstention.",
    ]
    if loop:
        lines.append(
            f"- Measured the full loop at {pct(loop['ex']['rate'])} execution accuracy on "
            f"{loop['n']} {name} questions (95% CI {interval(loop['ex'].get('exact'))}), "
            f"answering {pct(loop['answered']['rate'])} and correct on "
            f"{pct(loop['answered_only_ex']['rate'])} of answered questions."
        )
    point = _frozen_point(split)
    if point:
        lines.append(
            f"- With an agreement threshold chosen on development data before the {name} run, "
            f"the agent answered {pct(point['coverage'])} of {name} questions and was correct "
            f"on {pct(point['selective_ex'])} of the ones it answered."
        )
    if full:
        lines.append(
            f"- Reported honestly that a full-schema single-candidate baseline scored "
            f"{pct(full['ex']['rate'])} end to end on the same {name} questions, higher than "
            "the full loop, using paired bootstrap intervals for every ablation."
        )
    security = summary.get("security")
    if security:
        bound = security["success_rate_exact_95"]["high"]
        lines.append(
            f"- Recorded {security['attacks']} attacks with threat-specific success predicates; "
            f"{security['succeeded']} of {security['attacks']} succeeded (exact 95% upper bound "
            f"{pct(bound)}; recorded suite only). The guard accepts {security['gold_accepted']} "
            f"of {security['gold_items']} safe gold queries after a reviewed allowlist change "
            "(56 were blocked before D-076)."
        )
    layer_off = summary.get("layer_off")
    if layer_off:
        attacks = layer_off["configurations"]["all_layers_on"]["attacks"]
        kept = len(layer_off["prevented_with_any_one_layer_off"])
        single = "; ".join(
            f"{attack} depended on {LAYER_NAME.get(config, config)} alone"
            for attack, configs in layer_off["succeeded_with_one_layer_off"].items()
            for config in configs
        )
        lines.append(
            f"- Switched security layers off one at a time in a disposable database: {kept} of "
            f"{attacks} attacks stayed prevented with any single layer off"
            + (f"; {single}." if single else ".")
        )
    probe = summary.get("calibration_probe")
    if probe:
        lines.append(
            f"- Found by a {probe['n']}-question development probe that matching the model's "
            f"training prompt format raised accuracy from {probe['e0']}/{probe['n']} to "
            f"{probe['paper']}/{probe['n']} before freezing the evaluation contract."
        )
    return "\n".join([*lines, ""])


LAYER_NAME = {
    "guard_off": "the SQL guard",
    "privileges_off": "the restricted database role",
    "read_only_off": "the read-only transaction",
    "timeout_off": "the statement timeout",
}


def _frozen_point(split: dict[str, Any]) -> dict[str, Any] | None:
    coverage = split.get("accuracy_coverage") or {}
    threshold = coverage.get("frozen_threshold")
    return next((p for p in coverage.get("curve", []) if p["threshold"] == threshold), None)


def fmt_counts(counts: dict[str, int]) -> str:
    return ", ".join(f"{k.replace('_', ' ')} {v}" for k, v in counts.items()) or "none"
